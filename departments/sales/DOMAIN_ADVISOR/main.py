"""DOMAIN_ADVISOR: rule-based observations about each sales vertical, from deal records.

Every piece of advice comes from one named rule in RULES and carries the figures
that triggered it, so a sales lead can check it. Nothing is generated by a model
and nothing is acted on: these are prompts for a person.

  A1  fewer than `min_closed` closed deals       -> too little data to judge (no other rule runs)
  A2  more than half of won revenue              -> concentration risk
  A3  win rate 15+ points below the company's    -> review qualification and fit
  A4  win rate 15+ points above the company's    -> candidate for more prospecting
  A5  median cycle 1.5x the company's or longer  -> deals close slowly here
"""
import logging
import statistics
from typing import Any, Dict, List

from velaris.agentkit import biz_common as kit
from velaris.agentkit import biz_sales

logger = logging.getLogger("DOMAIN_ADVISOR")

RULES = {
    "A1": "Too few closed deals to judge this vertical; keep recording outcomes.",
    "A2": "More than half of won revenue comes from this vertical: a downturn there would hit hard.",
    "A3": "Win rate is well below the company average: review how these deals are qualified.",
    "A4": "Win rate is well above the company average: a candidate for more prospecting.",
    "A5": "Deals in this vertical take much longer to close than elsewhere: plan cash and capacity for it.",
}
CONCENTRATION_SHARE = 0.5
WIN_RATE_GAP = 0.15
SLOW_CYCLE_FACTOR = 1.5


class DOMAIN_ADVISORAgent:
    def __init__(self):
        self.name = "DOMAIN_ADVISOR"

    def health_check(self):
        return kit.health("DOMAIN_ADVISOR")

    def advise(self, deals: Any, min_closed: int = 5) -> Dict[str, Any]:
        if isinstance(min_closed, bool) or not isinstance(min_closed, int) or min_closed < 1:
            return kit.failed(["min_closed must be a whole number of at least 1"])
        parsed, errors = biz_sales.parse_deals(deals)
        if errors:
            return kit.failed(errors)
        if not parsed:
            return kit.needs_data("no deal records supplied", advice=[])
        won = sum(d["status"] == "won" for d in parsed)
        closed = won + sum(d["status"] == "lost" for d in parsed)
        overall_rate = won / closed if closed else None
        cycles = [(d["closed"] - d["opened"]).days for d in parsed
                  if d["status"] == "won" and d["opened"] and d["closed"]]
        overall_cycle = statistics.median(cycles) if cycles else None
        advice: List[Dict[str, Any]] = []

        def add(rule: str, vertical: str, evidence: str) -> None:
            advice.append({"rule": rule, "vertical": vertical, "advice": RULES[rule], "evidence": evidence})

        for r in biz_sales.vertical_stats(parsed):
            n = r["won"] + r["lost"]
            if n < min_closed:
                add("A1", r["vertical"], f"{n} closed deal(s), {min_closed} needed")
                continue
            if r["revenue_share"] is not None and r["revenue_share"] > CONCENTRATION_SHARE:
                add("A2", r["vertical"], f"{r['revenue_share']:.0%} of won revenue")
            gap = r["win_rate"] - overall_rate
            if gap <= -WIN_RATE_GAP:
                add("A3", r["vertical"], f"win rate {r['win_rate']:.0%} vs company {overall_rate:.0%} over {n} closed")
            elif gap >= WIN_RATE_GAP:
                add("A4", r["vertical"], f"win rate {r['win_rate']:.0%} vs company {overall_rate:.0%} over {n} closed")
            # `is not None`, not truthiness: a company median of 0 days is a real value (same-day closes), and a
            # vertical that takes days is then slow. A vertical at 0 days is never "slow".
            if overall_cycle is not None and r["median_cycle_days"] is not None and r["median_cycle_days"] > 0 \
                    and r["median_cycle_days"] >= SLOW_CYCLE_FACTOR * overall_cycle:
                add("A5", r["vertical"], f"median {r['median_cycle_days']} days vs company {overall_cycle} days")
        return {"status": "ok", "advice": advice,
                "company": {"win_rate": round(overall_rate, 4) if overall_rate is not None else None,
                            "median_cycle_days": overall_cycle, "closed_deals": closed},
                "rules": RULES, "thresholds": {"min_closed": min_closed, "concentration_share": CONCENTRATION_SHARE,
                                               "win_rate_gap": WIN_RATE_GAP, "slow_cycle_factor": SLOW_CYCLE_FACTOR},
                "note": "Observations for a person to weigh; nothing is acted on."}
