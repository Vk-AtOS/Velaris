import logging
from importlib import import_module

logger = logging.getLogger("ASEL")
handler = logging.StreamHandler()
handler.setFormatter(logging.Formatter("%(asctime)s - ASEL - %(levelname)s - %(message)s"))
if not logger.handlers:
    logger.addHandler(handler)
logger.setLevel(logging.DEBUG)

_COMPONENTS = ["ASEL_PLANNER", "ASEL_EXECUTOR", "ASEL_ROUTER", "ASEL_STRATEGIST", "ASEL_EVALUATOR"]

def _find_component():
    for comp in _COMPONENTS:
        try:
            mod = import_module(f"velaris.agents.{comp}.main")
            logger.debug(f"Loaded {comp}")
            return mod
        except ImportError as e:
            logger.debug("Delegate %s is not available: %s", comp, e)
        except Exception as e:
            logger.warning("Delegate %s failed to load: %s", comp, e)
    return None

class ASELAgent:
    def __init__(self, *args, **kwargs):
        self.name = "ASEL"
        self._component = _find_component()
        logger.debug(f"{self.name} initialized; delegate_loaded={bool(self._component)}")

    def health_check(self):
        if self._component and hasattr(self._component, "health_check"):
            try:
                return self._component.health_check()
            except Exception as e:
                # A delegate whose health check fails is not "ok".
                logger.warning("%s delegate health check failed: %s", self.name, e)
                return {"agent": self.name, "status": "degraded", "error": str(e), "version": "0.1.0"}
        return {"agent": self.name, "status": "ok", "version": "0.1.0"}

    def run(self, method: str, *args, **kwargs):
        if self._component and hasattr(self._component, method):
            return getattr(self._component, method)(*args, **kwargs)
        raise AttributeError(f"{self.name}: method {method} not found on delegate")

